export type MixLevel = 0 | 1 | 2 | 3;

/** Уровень ёрша по количеству смешанных типов напитков. */
export function mixLevelFor(typesCount: number): MixLevel {
  const t = BALANCE.mix.levelThresholds;
  if (typesCount >= t[2]) return 3;
  if (typesCount >= t[1]) return 2;
  if (typesCount >= t[0]) return 1;
  return 0;
}
